// Builds one limited palette per shot for the pixel style: renders sample frames of each shot
// (graded, before quantisation), clusters their colours with k-means and writes data/palettes.js.
//   node render/palettes.mjs [--k 28] [--workers 4]
import { chromium } from 'playwright';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, i, arr) => {
  if (a.startsWith('--')) acc.push([a.slice(2), arr[i + 1] && !arr[i + 1].startsWith('--') ? arr[i + 1] : '1']);
  return acc;
}, []));
const K = Number(args.k || 28), workers = Number(args.workers || 4);
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.woff2': 'font/woff2', '.json': 'application/json', '.mp3': 'audio/mpeg' };
const server = http.createServer((req, res) => {
  const p = path.join(ROOT, decodeURIComponent(new URL(req.url, 'http://x').pathname));
  if (!p.startsWith(ROOT) || !fs.existsSync(p) || fs.statSync(p).isDirectory()) { res.writeHead(404); res.end(); return; }
  res.writeHead(200, { 'Content-Type': MIME[path.extname(p)] || 'application/octet-stream' });
  fs.createReadStream(p).pipe(res);
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
// load without existing palettes so they don't influence anything
const url = `http://127.0.0.1:${server.address().port}/index.html?render=1&nopal=1`;
const browser = await chromium.launch({ args: ['--disable-gpu', '--disable-dev-shm-usage'] });
const p0 = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
await p0.goto(url);
const shots = await p0.evaluate(() => window.shotList());
await p0.close();
const out = {};
let next = 0;
const errors = [];
async function worker() {
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto(url);
  while (next < shots.length) {
    const s = shots[next++];
    const d = s.end - s.start, n = Math.max(3, Math.min(8, Math.round(d * 2)));
    const times = Array.from({ length: n }, (_, i) => s.start + 0.04 + (d - 0.08) * (i + 0.5) / n);
    const r = await page.evaluate(([tt, k]) => window.shotPalette(tt, k), [times, K]);
    out[r.name || s.name] = r.pal;
    process.stdout.write(`  ${s.name.padEnd(16)} ${r.pal.length} colours\n`);
  }
  await page.close();
}
await Promise.all(Array.from({ length: workers }, () => worker()));
await browser.close();
server.close();
if (errors.length) { console.error('ERRORS:\n' + [...new Set(errors)].slice(0, 10).join('\n')); process.exit(1); }
const ordered = Object.fromEntries(shots.map((s) => [s.name, out[s.name]]));
fs.writeFileSync(path.join(ROOT, 'data/palettes.js'), `// generated by render/palettes.mjs — one palette per shot for the pixel style\nwindow.NM_PALETTES = ${JSON.stringify(ordered, null, 0).replace(/\],"/g, '],\n"')};\n`);
console.log(`wrote ${Object.keys(ordered).length} palettes -> data/palettes.js`);
